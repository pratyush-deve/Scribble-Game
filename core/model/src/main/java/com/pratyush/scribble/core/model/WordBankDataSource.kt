    override fun getChoices(
        difficulty: WordDifficulty,
        count: Int,
        excludeWordIds: Set<String>
    ): List<WordChoice> {
        val combinedExcluded = synchronized(sessionOfferedWordIds) {
            excludeWordIds + sessionOfferedWordIds
        }

        // 1. Preferred pool: matching difficulty, excluding caller-excluded AND session-offered IDs
        var pool = entries
            .filter { it.difficulty == difficulty && it.id !in combinedExcluded }
            .distinctBy { it.word.trim().uppercase() }

        if (pool.size < count) {
            // Reset session history for this difficulty so we can cycle cleanly while still honoring caller's excludeWordIds
            val difficultyIds = entries.filter { it.difficulty == difficulty }.map { it.id }.toSet()
            synchronized(sessionOfferedWordIds) {
                sessionOfferedWordIds.removeAll(difficultyIds)
            }
            pool = entries
                .filter { it.difficulty == difficulty && it.id !in excludeWordIds }
                .distinctBy { it.word.trim().uppercase() }

            if (pool.size < count) {
                // Fallback: relax exclusion then difficulty
                pool = entries
                    .filter { it.difficulty == difficulty }
                    .distinctBy { it.word.trim().uppercase() }
                if (pool.size < count) {
                    pool = entries.distinctBy { it.word.trim().uppercase() }
                }
            }
        }

        val selected = pool.shuffled().take(count)
        synchronized(sessionOfferedWordIds) {
            selected.forEach { sessionOfferedWordIds.add(it.id) }
        }
        return selected.map { it.toWordChoice() }
    }

    override fun getWordById(id: String): WordBankEntry? {
        return entries.firstOrNull { it.id == id }
    }

